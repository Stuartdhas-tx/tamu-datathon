"""train_selector.py - learn which portfolio model beats which kind of opponent.

    python practice/train_selector.py                      # 40 generated opponents, 3 seeds
    python practice/train_selector.py --opponents 60 --seeds 4

For every TRAINING opponent (generated by opponents_gen.py; the named test
bots are never used here):
  1. profile: agent.py plays the first --profile-hands hands of a half, in
     both seats, and records the opponent's behaviour vector
     (bots/_features.py) exactly as the selector bot will see it live;
  2. performance: every portfolio model plays full duplicate matches against
     it (points per match, bb/deal).
Writes practice/tables/selector.json for bots/selector.py, which picks a
model from the most similar training opponents.
"""

import argparse
import json
import multiprocessing as mp
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "bots"))

import common  # noqa: E402
import opponents_gen  # noqa: E402

PORTFOLIO = ["agent", "greedy", "smallball", "poker-bot/agent.py"]
OUT = os.path.join(HERE, "tables", "selector.json")


def _profile(args):
    opp, seed, hands = args
    import _features
    from game import AgentConfig, Game, button_for_deal, make_deal
    me_bot, other = common.resolve("agent"), common.resolve(opp)
    vectors = []
    for half in (1, 2):
        me = half - 1
        me_bot.new_half(AgentConfig())
        other.new_half(AgentConfig())
        prof = _features.Profile()
        for d in range(hands):
            g = Game(make_deal(f"selector-profile-{seed}", d), button_for_deal(d), hand_index=d)
            last = None
            while not g.is_terminal:
                s = g.to_act
                o = g.observation(s)
                if s == me:
                    a = me_bot.act(o)
                    last = (o, int(a))
                else:
                    a = other.act(o)
                g.apply(a)
            prof.learn(last, g.hand_result(me))
            me_bot.end(g.hand_result(me))
            other.end(g.hand_result(1 - me))
        vectors.append(prof.vector())
    return ("profile", opp, vectors)


def _perf(args):
    model, opp, seed, deals = args
    r = common.play_match(model, opp, seed, deals)
    return ("perf", opp, model, r["points_a"], r["mean"])


def _job(args):
    return _profile(args[1:]) if args[0] == "profile" else _perf(args[1:])


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--opponents", type=int, default=40)
    p.add_argument("--seeds", type=int, default=3)
    p.add_argument("--deals", type=int, default=1000)
    p.add_argument("--profile-hands", type=int, default=150)
    p.add_argument("--procs", type=int, default=max(1, (os.cpu_count() or 2) - 1))
    a = p.parse_args()

    opps = opponents_gen.training_set(a.opponents)
    jobs = [("profile", o, s, a.profile_hands) for o in opps for s in range(a.seeds)]
    jobs += [("perf", m, o, f"selector-train-{s}", a.deals) for o in opps for m in PORTFOLIO
             for s in range(a.seeds)]
    print(f"{len(opps)} training opponents, {len(jobs)} jobs on {a.procs} processes...", file=sys.stderr)
    t0 = time.time()
    profiles, perf = {o: [] for o in opps}, {o: {m: [] for m in PORTFOLIO} for o in opps}
    with mp.Pool(a.procs) as pool:
        for i, res in enumerate(pool.imap_unordered(_job, jobs), 1):
            if res[0] == "profile":
                profiles[res[1]].extend(res[2])
            else:
                perf[res[1]][res[2]].append((res[3], res[4]))
            if i % max(1, len(jobs) // 10) == 0:
                print(f"  {i}/{len(jobs)} ({time.time() - t0:.0f}s)", file=sys.stderr)

    import _features
    n = len(_features.NAMES)
    allv = [v for o in opps for v in profiles[o]]
    mean = [sum(v[i] for v in allv) / len(allv) for i in range(n)]
    std = [max(1e-6, (sum((v[i] - mean[i]) ** 2 for v in allv) / len(allv)) ** 0.5) for i in range(n)]
    data = {
        "portfolio": PORTFOLIO, "default": "agent", "features": _features.NAMES,
        "profile_hands": a.profile_hands, "scale": {"mean": mean, "std": std},
        "opponents": [{
            "name": o,
            "profile": [sum(v[i] for v in profiles[o]) / len(profiles[o]) for i in range(n)],
            "points": {m: sum(x for x, _ in perf[o][m]) / len(perf[o][m]) for m in PORTFOLIO},
            "bb": {m: sum(y for _, y in perf[o][m]) / len(perf[o][m]) for m in PORTFOLIO},
        } for o in opps],
    }
    with open(OUT, "w") as fh:
        json.dump(data, fh, indent=1)

    print(f"\n{'opponent':34s}" + "".join(f"{m[-10:]:>12s}" for m in PORTFOLIO) + "   (points/match, bb/deal)")
    for o in data["opponents"]:
        print(f"{o['name']:34s}" + "".join(f"{o['points'][m]:5.2f}{o['bb'][m]:+6.2f} " for m in PORTFOLIO))
    tot = {m: sum(o["points"][m] for o in data["opponents"]) / len(opps) for m in PORTFOLIO}
    best = sum(max(o["points"].values()) for o in data["opponents"]) / len(opps)
    print("\nmean points/match: " + ", ".join(f"{m} {v:.3f}" for m, v in tot.items()) + f", per-opponent best {best:.3f}")
    print(f"saved {OUT}")


if __name__ == "__main__":
    main()
